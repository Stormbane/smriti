"""doc_facts.py -- the counts the docs state, generated from the code.

Counts, by static parsing (stdlib only; nothing is imported or run):

- CLI subcommands: ``add_parser("<name>")`` calls on the top-level
  subparsers object in ``src/smriti/cli.py``, plus the nested
  subcommands of any command that has its own subparsers;
- MCP tools: the ``name`` of every ``Tool(...)`` in the groups that
  ``src/smriti/mcp/tools/__init__.py`` joins into ``TOOLS`` (the core),
  and, listed apart, in the groups each profile's
  ``src/smriti/profiles/<name>/__init__.py`` joins into its own ``TOOLS``;
- test functions: ``test*`` functions at module level and in ``Test*``
  classes under ``tests/`` (pytest collects more items than this,
  because some tests are parametrised).

Usage::

    python scripts/doc_facts.py            # print the markdown snippet
    python scripts/doc_facts.py --write    # refresh it in README.md, CLAUDE.md, AGENTS.md
    python scripts/doc_facts.py --check    # exit 1 if any of those files is stale

The snippet sits between ``<!-- doc-facts:begin -->`` and
``<!-- doc-facts:end -->`` in each file. ``tests/test_doc_facts.py`` fails
when a stored snippet no longer matches the code.
"""

from __future__ import annotations

import argparse
import ast
import sys
import warnings
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CLI_PATH = REPO_ROOT / "src" / "smriti" / "cli.py"
MCP_TOOLS_DIR = REPO_ROOT / "src" / "smriti" / "mcp" / "tools"
PROFILES_DIR = REPO_ROOT / "src" / "smriti" / "profiles"
TESTS_DIR = REPO_ROOT / "tests"
DOC_FILES = ("README.md", "CLAUDE.md", "AGENTS.md")

BEGIN = "<!-- doc-facts:begin (generated by scripts/doc_facts.py; do not edit by hand) -->"
END = "<!-- doc-facts:end -->"
BEGIN_PREFIX = "<!-- doc-facts:begin"


@dataclass(frozen=True)
class Facts:
    commands: tuple[str, ...]
    subcommands: dict[str, tuple[str, ...]]
    tools: tuple[str, ...]  # the core's
    profile_tools: dict[str, tuple[str, ...]]  # profile name -> the tools it adds
    test_functions: int
    test_files: int


def _parse(path: Path) -> ast.Module:
    # Some test files carry invalid escape sequences; parsing them must not
    # print SyntaxWarnings over the snippet.
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", SyntaxWarning)
        return ast.parse(path.read_text(encoding="utf-8"), filename=str(path))


def _assignments(scope: ast.AST) -> list[tuple[str, ast.Call]]:
    """``name = <call>`` assignments in *scope*, in source order."""
    found = [
        (node.lineno, node.targets[0].id, node.value) for node in ast.walk(scope)
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and isinstance(node.value, ast.Call))
    ]
    return [(name, call) for _, name, call in sorted(found, key=lambda f: f[0])]


def _method_call(call: ast.Call, method: str) -> str | None:
    """The receiver's name when *call* is ``<name>.<method>(...)``."""
    func = call.func
    if (isinstance(func, ast.Attribute) and func.attr == method
            and isinstance(func.value, ast.Name)):
        return func.value.id
    return None


def _first_str_arg(call: ast.Call) -> str | None:
    if call.args and isinstance(call.args[0], ast.Constant) and isinstance(
            call.args[0].value, str):
        return call.args[0].value
    return None


def _is_root_parser(call: ast.Call) -> bool:
    """``ArgumentParser(prog="smriti", ...)``, however it is imported."""
    func = call.func
    named = (isinstance(func, ast.Attribute) and func.attr == "ArgumentParser") or (
        isinstance(func, ast.Name) and func.id == "ArgumentParser")
    return named and any(
        k.arg == "prog" and isinstance(k.value, ast.Constant) and k.value.value == "smriti"
        for k in call.keywords)


def cli_commands(path: Path = CLI_PATH) -> tuple[list[str], dict[str, list[str]]]:
    """Top-level subcommands, and nested ones keyed by their parent, in source order."""
    tree = _parse(path)
    # Only the function that builds the root parser: elsewhere in cli.py the
    # same variable names (``sub``, ``parser``) mean other things.
    scope = next(
        (fn for fn in ast.walk(tree)
         if isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef))
         and any(isinstance(n, ast.Call) and _is_root_parser(n) for n in ast.walk(fn))),
        None,
    )
    if scope is None:
        raise RuntimeError(f"no ArgumentParser(prog='smriti') found in {path}")

    root: str | None = None
    subparsers_of: dict[str, str] = {}  # subparsers var -> the parser var it belongs to
    parser_name: dict[str, str] = {}  # parser var -> the command it was registered as
    for name, call in _assignments(scope):
        if _is_root_parser(call):
            root = name
        elif (owner := _method_call(call, "add_subparsers")) is not None:
            subparsers_of[name] = owner
        elif _method_call(call, "add_parser") and (cmd := _first_str_arg(call)):
            parser_name[name] = cmd

    calls = sorted(
        (n for n in ast.walk(scope) if isinstance(n, ast.Call)),
        key=lambda n: (n.lineno, n.col_offset),
    )
    top: list[str] = []
    nested: dict[str, list[str]] = {}
    for node in calls:
        receiver = _method_call(node, "add_parser")
        name = _first_str_arg(node)
        if receiver is None or name is None or receiver not in subparsers_of:
            continue
        owner = subparsers_of[receiver]
        if owner == root:
            top.append(name)
        elif owner in parser_name:
            nested.setdefault(parser_name[owner], []).append(name)
    return top, nested


def _module_tools(path: Path) -> ast.Tuple | None:
    """The module-level ``TOOLS = (...)`` tuple in ``path``, or None."""
    for node in _parse(path).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target, value = node.targets[0], node.value
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            target, value = node.target, node.value
        else:
            continue
        if isinstance(target, ast.Name) and target.id == "TOOLS" and isinstance(value, ast.Tuple):
            return value
    return None


def _required_tools(path: Path) -> ast.Tuple:
    tools = _module_tools(path)
    if tools is None:
        raise RuntimeError(f"no module-level TOOLS tuple found in {path}")
    return tools


def joined_tools(init: Path) -> list[str]:
    """Tool names, in order, of the groups that *init* joins into ``TOOLS``.

    *init* joins the groups (``TOOLS = (*memory.TOOLS, ...)``); each group is
    a module beside it that lists ``Tool(name="...", ...)`` entries.
    """
    names: list[str] = []
    for group in _required_tools(init).elts:
        if not (isinstance(group, ast.Starred) and isinstance(group.value, ast.Attribute)
                and isinstance(group.value.value, ast.Name)):
            raise RuntimeError(f"unexpected entry in {init} TOOLS")
        for entry in _required_tools(init.parent / f"{group.value.value.id}.py").elts:
            name = next((kw.value.value for kw in getattr(entry, "keywords", [])
                         if kw.arg == "name" and isinstance(kw.value, ast.Constant)), None)
            if isinstance(name, str):
                names.append(name)
    return names


def mcp_tools(tools_dir: Path = MCP_TOOLS_DIR) -> list[str]:
    """The core's tool names in ``tools/list`` order."""
    return joined_tools(tools_dir / "__init__.py")


def profile_tools(profiles_dir: Path = PROFILES_DIR) -> dict[str, list[str]]:
    """Each profile's added tool names, by profile; a profile without ``TOOLS`` adds none."""
    found: dict[str, list[str]] = {}
    for init in sorted(profiles_dir.glob("*/__init__.py")):
        if _module_tools(init) is not None:
            found[init.parent.name] = joined_tools(init)
    return found


def _is_test(node: ast.AST) -> bool:
    return isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith(
        "test")


def count_tests(tests_dir: Path = TESTS_DIR) -> tuple[int, int]:
    """(test functions, test files) under *tests_dir*."""
    functions = files = 0
    for path in sorted(tests_dir.rglob("test_*.py")):
        tree = _parse(path)
        found = 0
        for node in tree.body:
            if _is_test(node):
                found += 1
            elif isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
                found += sum(1 for item in node.body if _is_test(item))
        functions += found
        files += 1 if found else 0
    return functions, files


def collect(repo_root: Path = REPO_ROOT) -> Facts:
    top, nested = cli_commands(repo_root / "src" / "smriti" / "cli.py")
    tools = mcp_tools(repo_root / "src" / "smriti" / "mcp" / "tools")
    profiles = profile_tools(repo_root / "src" / "smriti" / "profiles")
    functions, files = count_tests(repo_root / "tests")
    return Facts(
        commands=tuple(top),
        subcommands={k: tuple(v) for k, v in nested.items()},
        tools=tuple(tools),
        profile_tools={k: tuple(v) for k, v in profiles.items()},
        test_functions=functions,
        test_files=files,
    )


def snippet(facts: Facts) -> str:
    """The markdown block the docs carry, markers included."""
    def ticks(names: tuple[str, ...]) -> str:
        return ", ".join(f"`{n}`" for n in names)

    nested = "; ".join(
        f"`{parent}` has {ticks(children)}"
        for parent, children in sorted(facts.subcommands.items())
    )
    lines = [
        BEGIN,
        f"- **CLI:** {len(facts.commands)} `smriti` subcommands: "
        f"{ticks(tuple(sorted(facts.commands)))}."
        + (f" Nested: {nested}." if nested else ""),
        f"- **MCP:** {len(facts.tools)} core tools: {ticks(facts.tools)}.",
        *(f"- **MCP, `{name}` profile:** {len(tools)} more tools when it is enabled: "
          f"{ticks(tools)}."
          for name, tools in sorted(facts.profile_tools.items()) if tools),
        f"- **Tests:** {facts.test_functions} test functions in {facts.test_files} files "
        "under `tests/` (pytest collects more, because some are parametrised).",
        END,
    ]
    return "\n".join(lines)


def stored_snippet(text: str) -> str | None:
    """The doc-facts block in *text*, markers included, or None."""
    start = text.find(BEGIN_PREFIX)
    if start < 0:
        return None
    end = text.find(END, start)
    if end < 0:
        return None
    return text[start:end + len(END)]


def refresh(text: str, block: str) -> str:
    current = stored_snippet(text)
    if current is None:
        raise ValueError("no doc-facts markers in the file")
    return text.replace(current, block, 1)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true",
                      help="refresh the block in README.md, CLAUDE.md and AGENTS.md")
    mode.add_argument("--check", action="store_true",
                      help="exit 1 if any of those files carries a stale block")
    args = parser.parse_args(argv)

    block = snippet(collect())
    if not (args.write or args.check):
        print(block)
        return 0

    stale: list[str] = []
    for name in DOC_FILES:
        path = REPO_ROOT / name
        # Text mode reads CRLF as LF, so blocks compare equal on any checkout;
        # a refresh keeps the file's own line endings.
        newline = "\r\n" if b"\r\n" in path.read_bytes() else "\n"
        text = path.read_text(encoding="utf-8")
        if stored_snippet(text) is None:
            print(f"{name}: no doc-facts markers", file=sys.stderr)
            stale.append(name)
            continue
        if stored_snippet(text) == block:
            continue
        if args.write:
            path.write_text(refresh(text, block), encoding="utf-8", newline=newline)
            print(f"{name}: refreshed")
        else:
            stale.append(name)
    if stale:
        print("stale: " + ", ".join(stale) + " (run: python scripts/doc_facts.py --write)",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
