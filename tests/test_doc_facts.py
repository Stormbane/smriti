"""The counts the docs state must match the code.

README.md, CLAUDE.md and AGENTS.md each carry a block generated by
``scripts/doc_facts.py`` (CLI subcommands, MCP tools, test functions).
The 2026-11-04 comprehension baseline found every fresh agent repeating
stale hand-written counts ("39 passing", "11 commands", "three tools"),
so a drifted block fails here. Fix: ``python scripts/doc_facts.py --write``.
"""

from __future__ import annotations

import ast
import importlib.util
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

REPO = Path(__file__).resolve().parents[1]
FIX = "run: python scripts/doc_facts.py --write"


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("doc_facts", REPO / "scripts" / "doc_facts.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("doc_facts", module)
    spec.loader.exec_module(module)
    return module


doc_facts = _load()


@pytest.fixture(scope="module")
def facts() -> Any:
    return doc_facts.collect(REPO)


@pytest.mark.parametrize("name", doc_facts.DOC_FILES)
def test_stored_counts_match_the_code(name: str, facts: Any) -> None:
    text = (REPO / name).read_text(encoding="utf-8")
    stored = doc_facts.stored_snippet(text)
    assert stored is not None, f"{name} has no doc-facts block; {FIX}"
    assert stored == doc_facts.snippet(facts), f"{name}: stated counts drifted; {FIX}"


def _handler_keys() -> set[str]:
    """Keys of the ``handlers`` dict in cli.main: what actually dispatches."""
    tree = ast.parse((REPO / "src" / "smriti" / "cli.py").read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and node.targets[0].id == "handlers" and isinstance(node.value, ast.Dict)):
            return {k.value for k in node.value.keys if isinstance(k, ast.Constant)}
    raise AssertionError("no handlers dict in cli.py")


def test_parsed_commands_are_the_dispatched_ones(facts: Any) -> None:
    # Guards the parser in doc_facts.py, not the docs.
    assert set(facts.commands) == _handler_keys()
    assert len(facts.commands) == len(set(facts.commands))


def _every_tool(facts: Any) -> list[str]:
    return [*facts.tools, *(t for tools in facts.profile_tools.values() for t in tools)]


def test_tool_names_are_unique(facts: Any) -> None:
    every = _every_tool(facts)
    assert facts.tools and len(every) == len(set(every))


def test_the_static_tool_lists_are_the_served_ones(facts: Any) -> None:
    # Guards the parser in doc_facts.py: what it reads is what the code serves.
    from smriti.mcp.tools import TOOLS
    from smriti.profiles import load_profile

    assert facts.tools == tuple(t.name for t in TOOLS)
    assert facts.profile_tools, "no profile tools found"
    for name, tools in facts.profile_tools.items():
        assert tools == tuple(t.name for t in load_profile(name).tools)


def test_readme_tables_name_every_command_and_tool(facts: Any) -> None:
    """The hand-written tables that classify each interface must be complete."""
    text = (REPO / "README.md").read_text(encoding="utf-8")
    stored = doc_facts.stored_snippet(text) or ""
    prose = text.replace(stored, "")
    missing = [f"smriti {c}" for c in facts.commands if f"`smriti {c}" not in prose]
    missing += [t for t in _every_tool(facts) if f"`{t}" not in prose]
    assert not missing, f"README.md tables don't mention: {', '.join(missing)}"


def test_snippet_round_trips() -> None:
    block = doc_facts.snippet(doc_facts.collect(REPO))
    doc = f"# Title\n\nbefore\n\n{doc_facts.BEGIN}\nold\n{doc_facts.END}\n\nafter\n"
    refreshed = doc_facts.refresh(doc, block)
    assert doc_facts.stored_snippet(refreshed) == block
    assert refreshed.startswith("# Title\n\nbefore\n\n") and refreshed.endswith("\n\nafter\n")
